"""
Gera `src/lib/pdf-editorial/letras.ts` — as letras do PDF da proposta (23/10).

Jost 400 (tudo o resto: títulos, sobretítulos, notas, números, valores,
rótulos, rodapé — «letra simples», a escolha dela de 23/10) e Bodoni Moda
normal, só no preço total. O
documento dela (§3) pede o tamanho óptico 96; aqui fixa-se em opsz=6, wght=500,
porque no 96 os traços finos desaparecem num telemóvel (ver em baixo). O
subconjunto «latin» do @fontsource 5.3.0; a Bodoni vem do pacote variável
(@fontsource-variable/bodoni-moda).

Passa de WOFF2 a TTF simples: o subsetting do pdf-lib/fontkit não é de
confiança em tabelas embrulhadas em WOFF (o mesmo motivo do `proposal-fonts.ts`).

Uso (com `pip install fonttools brotli`):
  python3 scripts/gerar-letras-do-pdf.py <jost-latin-400-normal.woff2> \
      <bodoni-moda-latin-opsz-normal.woff2>
"""
import base64
import io
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SAIDA = "src/lib/pdf-editorial/letras.ts"


def estatica(caminho, eixos=None):
    f = TTFont(caminho)
    if eixos and "fvar" in f:
        f = instantiateVariableFont(f, eixos)
    f.flavor = None
    b = io.BytesIO()
    f.save(b)
    return base64.b64encode(b.getvalue()).decode("ascii")


jost, bodoni = sys.argv[1:3]
# O TAMANHO ÓPTICO por papel, e não o 96 do documento. O pedido dela de 23/10,
# com o PDF aberto no iPhone: «estes números não dá para perceber nada». No
# opsz 96 o traço fino da Bodoni mede 0,2 % do corpo — a página inteira num
# telemóvel tem ~390 px de largura, e o traço fino do preço de 85 px ficava
# com 0,06 px de ecrã: desaparece. No opsz 6 (o mínimo do eixo) mede 3,4 % —
# o preço fica com 1 px de ecrã. O peso 500 engrossa as hastes, não o traço
# fino (medido: `docs/PDF-DESIGN-NOVO.md`, Parte −1).
eixos = {"opsz": 6, "wght": 500}
linhas = [
    "// AUTO-GENERATED by scripts/gerar-letras-do-pdf.py — do not edit by hand.",
    "//",
    "// As letras do PDF da proposta (docs/PDF-DESIGN-NOVO.md, 23/10): Jost 400 e",
    "// Bodoni Moda no tamanho óptico 6, peso 500, só para o preço total — o mais",
    "// legível num telemóvel (ver o gerador). Subconjunto «latin» do @fontsource 5.3.0,",
    "// passado de WOFF2 a TTF simples com o fontTools.",
    "//",
    "// SIL Open Font License 1.1 — ver src/lib/fonts/Jost-OFL-LICENSE.txt e",
    "// src/lib/fonts/BodoniModa-OFL-LICENSE.txt.",
    "",
    f'export const JOST_400_TTF_B64 =\n  "{estatica(jost)}";',
    "",
    "/** O preço total, e só ele (Bodoni Moda normal). */",
    f'export const BODONI_PRECO_TTF_B64 =\n  "{estatica(bodoni, eixos)}";',
    "",
]
open(SAIDA, "w").write("\n".join(linhas))
print("escrito", SAIDA)
