"""
Gera `src/lib/pdf-editorial/letras.ts` — as letras do PDF da proposta (23/10).

Jost 400 (corpo, títulos em maiúsculas, rótulos, rodapé) e Bodoni Moda 400,
normal e itálico, no TAMANHO ÓPTICO 96 (o documento dela, `docs/PDF-DESIGN-NOVO.md`
§3). O subconjunto «latin» do @fontsource 5.3.0; a Bodoni vem do pacote
variável (@fontsource-variable/bodoni-moda) e fixa-se aqui em opsz=96, wght=400.

Passa de WOFF2 a TTF simples: o subsetting do pdf-lib/fontkit não é de
confiança em tabelas embrulhadas em WOFF (o mesmo motivo do `proposal-fonts.ts`).

Uso (com `pip install fonttools brotli`):
  python3 scripts/gerar-letras-do-pdf.py <jost-latin-400-normal.woff2> \
      <bodoni-moda-latin-opsz-normal.woff2> <bodoni-moda-latin-opsz-italic.woff2>
"""
import base64
import io
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SAIDA = "src/lib/pdf-editorial/letras.ts"


def estatica(caminho, eixos=None):
    f = TTFont(caminho)
    if eixos and "fvar" in f:
        f = instantiateVariableFont(f, eixos)
    f.flavor = None
    b = io.BytesIO()
    f.save(b)
    return base64.b64encode(b.getvalue()).decode("ascii")


jost, bodoni, bodoni_it = sys.argv[1:4]
eixos = {"opsz": 96, "wght": 400}
linhas = [
    "// AUTO-GENERATED by scripts/gerar-letras-do-pdf.py — do not edit by hand.",
    "//",
    "// As letras do PDF da proposta (docs/PDF-DESIGN-NOVO.md, 23/10): Jost 400 e",
    "// Bodoni Moda 400 normal e itálico no tamanho óptico 96. Subconjunto «latin» do",
    "// @fontsource 5.3.0, passado de WOFF2 a TTF simples com o fontTools.",
    "//",
    "// SIL Open Font License 1.1 — ver src/lib/fonts/Jost-OFL-LICENSE.txt e",
    "// src/lib/fonts/BodoniModa-OFL-LICENSE.txt.",
    "",
    f'export const JOST_400_TTF_B64 =\n  "{estatica(jost)}";',
    "",
    f'export const BODONI_400_TTF_B64 =\n  "{estatica(bodoni, eixos)}";',
    "",
    f'export const BODONI_400_ITALICO_TTF_B64 =\n  "{estatica(bodoni_it, eixos)}";',
    "",
]
open(SAIDA, "w").write("\n".join(linhas))
print("escrito", SAIDA)
