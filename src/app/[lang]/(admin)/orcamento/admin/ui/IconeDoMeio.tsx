/**
 * O ícone de um meio de pagamento (ver `lib/orcamento/meios-de-pagamento.ts`).
 *
 * ── MB WAY E MULTIBANCO: OS LOGÓTIPOS OFICIAIS (5/11) ──────────────────────
 *
 * Ela pediu «os logos oficiais dos meios de pagamento». Só dois têm marca:
 * MB WAY e Multibanco, ambos da SIBS. Os traços são os ficheiros da própria
 * SIBS, tal como estão no Wikimedia Commons («File:Logo MBWay.svg», tirado de
 * mbway.pt, e «File:Multibanco.svg»), com as cores deles (#ff0000 e #3d73b9,
 * texto #1d1d1b). Nada foi redesenhado. Duas mudanças, ambas técnicas:
 *
 *   · as cores passaram das classes `.cls-1`/`.cls-2` para `fill` em cada
 *     traço. Os dois ficheiros usam os MESMOS nomes de classe com cores
 *     diferentes, e dois `<style>` na mesma página pintavam o Multibanco de
 *     vermelho;
 *   · do Multibanco fica o SÍMBOLO (os parênteses azuis e o «MB», o que está
 *     em cada caixa). A palavra «MULTIBANCO» por baixo teria 1,5 px num chip;
 *     o nome do meio já está escrito ao lado.
 *
 * Ficam sobre um rectângulo BRANCO nos dois temas: o «MB» é quase preto e
 * desaparecia no fundo escuro, e é assim que os logótipos de pagamento se
 * mostram (sem recolorir a marca). São cores da marca, não da casa — por isso
 * não passam pelos tokens.
 *
 * Os outros (transferência, numerário, cheque, e o que não se reconhece) não
 * têm marca: continuam os traços da Lucide (licença ISC), a biblioteca que o
 * sistema de design manda usar (§8.1). Tudo decorativo — o nome do meio está
 * sempre escrito ao lado.
 */
export function IconeDoMeio({ meio, tamanho = 14 }: { meio: MeioDePagamento; tamanho?: number }) {
  if (meio === "mbway" || meio === "multibanco") {
    const logo = LOGOS[meio];
    return (
      <span
        aria-hidden="true"
        data-meio={meio}
        data-logo-oficial=""
        className="inline-flex shrink-0 items-center justify-center rounded-[4px] bg-white px-[3px] ring-1 ring-black/10"
        style={{ height: tamanho + 4 }}
      >
        <svg
          height={tamanho}
          width={Math.round(tamanho * logo.proporcao)}
          viewBox={logo.viewBox}
          focusable="false"
        >
          {logo.tracos}
        </svg>
      </span>
    );
  }
  return (
    <svg
      width={tamanho}
      height={tamanho}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className="shrink-0"
      data-meio={meio}
    >
      {TRACOS[meio]}
    </svg>
  );
}

